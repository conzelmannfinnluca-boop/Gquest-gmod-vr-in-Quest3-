"""Compile the measured HL2 idle hand poses; ArcVR is retired."""
from pathlib import Path
import hashlib
import json
import math

ROOT=Path(__file__).resolve().parent
measured=json.loads((ROOT/'gquest-hl2-authored-fingers.json').read_text())
profiles={}
provenance={}
for key,item in sorted(measured['weapons'].items()):
    # GMod tool/camera/medkit export additive/reference animations. They are
    # explicitly excluded: a complete bone list is not a verified grip pose.
    if not key.startswith('weapon_') or key=='weapon_medkit':continue
    assert item['complete'] and item['sequence']=='idle',key
    closed=item['angles']
    assert len(closed)==15 and all(len(v)==3 for v in closed)
    assert all(math.isfinite(x) and abs(x)<=180 for a in closed for x in a)
    opened=[a.copy() for a in closed]
    if key not in {'weapon_crowbar','weapon_frag','weapon_bugbait'}:
        # Original idle is the contact pose. Ease the distal index joints away
        # from the trigger on release; preserve every other authored joint.
        opened[3][2]-=7
        opened[4][1]=min(10,opened[4][1]+10)
        opened[5][1]=min(0,opened[5][1]+25)
    profiles[key]=opened+closed
    model=ROOT/'quest-vr-content'/item['model']
    assert model.is_file(),model
    provenance[key]={'source':'Quest model bone matrices relative to player neutral skeleton',
        'model':item['model'],'model_sha256':hashlib.sha256(model.read_bytes()).hexdigest(),
        'sequence':item['sequence'],'reference':measured['reference'],
        'index_release':'three bounded index changes' if opened!=closed else 'authored grip retained'}
assert len(profiles)==12
header='// Generated by work/generate_native_finger_profiles.py.\n'
header+=f'static constexpr int GquestFingerProfileCount={len(profiles)};\n'
header+='static constexpr const char* GquestFingerProfileNames[]={'+','.join(json.dumps(k) for k in profiles)+'};\n'
header+=f'static constexpr float GquestFingerProfiles[{len(profiles)}][30][3]={{\n'
for values in profiles.values():
    assert len(values)==30
    header+='{'+','.join('{'+','.join(repr(float(x))+'f' for x in a)+'}' for a in values)+'},\n'
header+='};\n'
(ROOT/'gquest_native_finger_profiles.h').write_text(header)
(ROOT/'gquest-native-finger-profile-manifest.json').write_text(json.dumps(provenance,indent=2)+'\n')
print(f'{len(profiles)} native grip profiles; unposed GMod animation layers excluded')
